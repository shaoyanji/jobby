//go:build ignore

// gen-metrics writes the Helvetica width tables used by the layout compiler.
// It reads pdfcpu's bundled Core14 AFMs and WinAnsi glyph map, so the numbers
// are the same ones pdfcpu uses when it renders the text.
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	mod := os.Getenv("PDFCPU_MOD")
	if mod == "" {
		fmt.Fprintln(os.Stderr, "set PDFCPU_MOD to the pdfcpu module directory")
		os.Exit(1)
	}
	names := winAnsiNames(filepath.Join(mod, "internal/corefont/metrics/standard.go"))
	faces := []struct {
		file  string
		ident string
	}{
		{"Helvetica.afm", "helvetica"},
		{"Helvetica-Bold.afm", "helveticaBold"},
		{"Helvetica-Oblique.afm", "helveticaOblique"},
	}

	var b strings.Builder
	b.WriteString("// Code generated by gen-metrics; DO NOT EDIT.\n\n")
	b.WriteString("// Widths are in 1/1000 em, indexed by WinAnsi code, taken from the Core14\n")
	b.WriteString("// AFMs pdfcpu renders with. Missing codes are zero.\n\n")
	b.WriteString("package layout\n\n")
	b.WriteString("var winAnsiWidths = map[face][256]int16{\n")
	for _, f := range faces {
		widths := afmWidths(filepath.Join(mod, "internal/corefont/Core14_AFMs", f.file))
		b.WriteString("\t" + f.ident + ": {\n")
		for code := 0; code < 256; code += 16 {
			b.WriteString("\t\t")
			for c := code; c < code+16; c++ {
				name := names[c]
				w, ok := widths[name]
				if !ok || name == "" {
					w = 0
				}
				b.WriteString(strconv.Itoa(w) + ", ")
			}
			b.WriteString("\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	fmt.Print(b.String())
}

var winAnsiLine = regexp.MustCompile(`^\s*(\d+):\s*"([^"]*)"`)

func winAnsiNames(path string) [256]string {
	var out [256]string
	b, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	// The file holds several encoding maps (WinAnsi, MacRoman, PDFDoc,
	// Symbol, ZapfDingbats); only the first block is the one pdfcpu renders
	// Latin text with.
	src := string(b)
	start := strings.Index(src, "var WinAnsiGlyphMap")
	if start < 0 {
		panic("WinAnsiGlyphMap not found")
	}
	end := strings.Index(src[start:], "\n}\n")
	if end < 0 {
		panic("unterminated WinAnsiGlyphMap")
	}
	block := src[start : start+end]
	for _, line := range strings.Split(block, "\n") {
		m := winAnsiLine.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		code, _ := strconv.Atoi(m[1])
		if code >= 0 && code < 256 {
			out[code] = m[2]
		}
	}
	return out
}

var afmLine = regexp.MustCompile(`^C\s+(-?\d+)\s*;\s*WX\s+(-?\d+)\s*;\s*N\s+(\S+)`)

func afmWidths(path string) map[string]int {
	out := map[string]int{}
	f, err := os.Open(path)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := afmLine.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		w, _ := strconv.Atoi(m[2])
		out[m[3]] = w
	}
	return out
}
